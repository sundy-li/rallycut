#!/usr/bin/env python3
"""Assemble a repo-independent skill from shared canonical vision sources."""
import argparse
import importlib.util
import hashlib
import json
from pathlib import Path
import os
import shutil
import subprocess
import tempfile
import zipfile
_spec=importlib.util.spec_from_file_location('rallycut_runtime_import_check',Path(__file__).with_name('check_runtime_imports.py'))
_checker=importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_checker)
check_runtime_imports=_checker.check

REPO=Path(__file__).resolve().parents[1]
NAME='rallycut-video-json'
RUNTIME_FILES=(
    'headless.py','neural_analysis.py','backends.py','coreml_model.py','coreml_process.py','pretrained.py','visual.py','audio_features.py','table_locator.py','table_jump.py','shot_boundary.py','inference_pipeline.py','performance.py','video_decode.py','rally_state.py','rally_activity.py','rally_transits.py','rally_serves.py','play_area.py','net_geometry.py','detection_cache.py',
    'download_model.py','requirements.txt','requirements-model.txt','requirements-decode.txt',
    'vendor/blurball/network.py','vendor/blurball/config.json',
    'vendor/blurball/LICENSE.md','vendor/blurball/HRNET-LICENSE','vendor/blurball/NOTICE.md',
)
SKILL_FILES=('SKILL.md','scripts/rallycut.py','references/output-schema.md','references/setup.md','references/agent-editing.md')
# rallycut-cli (cmd/rallycut-cli): plan / export / brief with the desktop's own
# timeline and FFmpeg export code. Pure Go, cross-compiled; no Go at runtime.
TOOL_PLATFORMS=('darwin-arm64','darwin-amd64','linux-amd64','linux-arm64','windows-amd64')


def build_tools(target):
    """Cross-compile rallycut-cli into target/<os>-<arch>/; returns {relative: sha256}."""
    go=shutil.which('go')
    if not go:
        raise ValueError('Go is required to build the skill package (not to run it)')
    flags=subprocess.run(['bash',str(REPO/'scripts/build-ldflags.sh')],check=True,capture_output=True,text=True,cwd=REPO).stdout
    tools={}
    for platform in TOOL_PLATFORMS:
        goos,goarch=platform.split('-')
        name='rallycut-cli.exe' if goos=='windows' else 'rallycut-cli'
        out=target/platform/name
        out.parent.mkdir(parents=True,exist_ok=True)
        env={**os.environ,'GOOS':goos,'GOARCH':goarch,'CGO_ENABLED':'0'}
        subprocess.run([go,'build','-trimpath','-buildvcs=false','-ldflags','-s -w '+flags,'-o',str(out),'./cmd/rallycut-cli'],
                       check=True,cwd=REPO,env=env)
        out.chmod(0o755)
        tools[out.relative_to(target.parent).as_posix()]=hashlib.sha256(out.read_bytes()).hexdigest()
    return tools


def build(output):
    output=Path(output).resolve()
    folder=output/NAME
    if folder==REPO/'skills'/NAME:
        raise ValueError('refusing to replace the skill source template')
    if folder.exists() and not (folder/'assets/runtime/runtime-manifest.json').is_file():
        raise ValueError('refusing to replace a directory not generated by this builder')
    output.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.rallycut-skill-',dir=output) as temporary:
        stage=Path(temporary)/NAME
        for relative in SKILL_FILES:
            source=REPO/'skills'/NAME/relative
            if source.is_symlink():
                raise ValueError('symlink in skill source')
            target=stage/relative
            target.parent.mkdir(parents=True,exist_ok=True)
            shutil.copyfile(source,target)
        skill=(stage/'SKILL.md').read_text(encoding='utf-8')
        if not skill.startswith('---\nname: '+NAME+'\n') or '\ndescription: ' not in skill or 'TODO' in skill:
            raise ValueError('invalid/incomplete skill frontmatter')
        runtime=stage/'assets/runtime'
        checks={}
        for relative in RUNTIME_FILES:
            source=REPO/'vision'/relative
            if source.is_symlink():
                raise ValueError('symlink in runtime source')
            target=runtime/relative
            target.parent.mkdir(parents=True,exist_ok=True)
            shutil.copyfile(source,target)
            checks[relative]=hashlib.sha256(target.read_bytes()).hexdigest()
        check_runtime_imports(REPO/'vision',runtime)
        digest=hashlib.sha256(''.join(f'{path}\0{checks[path]}\n' for path in sorted(checks)).encode()).hexdigest()
        # Tools are hashed separately: rebuilding the CLI must not move the
        # Python runtime cache, which is keyed by `digest`.
        tools=build_tools(stage/'assets/bin')
        (runtime/'runtime-manifest.json').write_text(json.dumps({'schema_version':1,'digest':digest,'files':checks,'tools':tools},indent=2)+'\n')
        folder=output/NAME
        if folder.exists():
            shutil.rmtree(folder)
        shutil.copytree(stage,folder)
        archive=output/(NAME+'.skill')
        with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as package:
            for path in sorted(folder.rglob('*')):
                if path.is_file():
                    package.write(path,path.relative_to(output).as_posix())
    return folder,archive,digest


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--output',type=Path,default=REPO/'build/skills')
    args=parser.parse_args()
    folder,archive,digest=build(args.output)
    print(json.dumps({'skill':str(folder),'package':str(archive),'runtime_digest':digest}))


if __name__=='__main__':
    main()
